CREATE TABLE companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    address VARCHAR(500) NOT NULL,
    website VARCHAR(1000) NOT NULL
);
CREATE TABLE jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    salary_from NUMERIC(15, 2) NOT NULL,
    salary_to NUMERIC(15, 2) NOT NULL,
    location VARCHAR(200) NOT NULL,
    status VARCHAR(10) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_jobs_company FOREIGN KEY (company_id) REFERENCES companies(id),
    CONSTRAINT ck_jobs_salary CHECK (salary_from >= 0 AND salary_to >= salary_from),
    CONSTRAINT ck_jobs_status CHECK (status IN ('OPEN', 'CLOSED'))
);
CREATE TABLE applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL,
    full_name VARCHAR(200) NOT NULL,
    email VARCHAR(254) NOT NULL,
    cv_url VARCHAR(2000) NOT NULL,
    applied_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_applications_job FOREIGN KEY (job_id) REFERENCES jobs(id),
    CONSTRAINT uk_applications_job_email UNIQUE (job_id, email)
);
CREATE INDEX idx_jobs_company ON jobs(company_id);
CREATE INDEX idx_jobs_status ON jobs(status);
